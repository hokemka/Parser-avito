_premium_enabled = True


def configure(enabled: bool) -> None:
    global _premium_enabled
    _premium_enabled = enabled


def is_enabled() -> bool:
    return _premium_enabled


def em(name: str) -> str:
    fallback, emoji_id = PREMIUM_EMOJI[name]
    if not _premium_enabled:
        return fallback
    return f'<tg-emoji emoji-id="{emoji_id}">{fallback}</tg-emoji>'


def icon(name: str) -> str | None:
    if not _premium_enabled:
        return None
    return PREMIUM_EMOJI[name][1]


def plain(name: str) -> str:
    return PREMIUM_EMOJI[name][0]
